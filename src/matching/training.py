def optimize_memory_usage(df: pd.DataFrame, verbose: bool = False) -> pd.DataFrame:
    """
    Downcast numeric data types in DataFrame to reduce memory footprint by 50-75%.
    
    Useful for running multi-million pair datasets in Google Colab memory limits.
    
    Args:
        df: Input pandas DataFrame.
        verbose: If True, log memory reduction statistics.
        
    Returns:
        DataFrame with optimized data types.
    """
    start_mem = df.memory_usage().sum() / 1024**2 if not df.empty else 0.0

    for col in df.columns:
        col_type = df[col].dtype

        if pd.api.types.is_integer_dtype(col_type):
            c_min = df[col].min()
            c_max = df[col].max()
            if c_min >= 0:
                if c_max < 255:
                    df[col] = df[col].astype(np.uint8)
                elif c_max < 65535:
                    df[col] = df[col].astype(np.uint16)
                elif c_max < 4294967295:
                    df[col] = df[col].astype(np.uint32)
            else:
                if c_min > np.iinfo(np.int8).min and c_max < np.iinfo(np.int8).max:
                    df[col] = df[col].astype(np.int8)
                elif c_min > np.iinfo(np.int16).min and c_max < np.iinfo(np.int16).max:
                    df[col] = df[col].astype(np.int16)
                elif c_min > np.iinfo(np.int32).min and c_max < np.iinfo(np.int32).max:
                    df[col] = df[col].astype(np.int32)

        elif pd.api.types.is_float_dtype(col_type):
            df[col] = df[col].astype(np.float32)

    end_mem = df.memory_usage().sum() / 1024**2 if not df.empty else 0.0
    if verbose:
        logger.info(
            "Memory usage decreased from %.2f MB to %.2f MB (%.1f%% reduction)",
            start_mem,
            end_mem,
            100 * (start_mem - end_mem) / start_mem if start_mem > 0 else 0,
        )
    return df


def create_batches(
    df: pd.DataFrame,
    batch_size: int = 100000,
) -> Generator[pd.DataFrame, None, None]:
    """
    Yield slices of DataFrame in chunks for memory-efficient batch processing.
    
    Args:
        df: Input DataFrame.
        batch_size: Number of rows per batch.
        
    Yields:
        DataFrame chunks of size at most batch_size.
    """
    n_rows = len(df)
    for start_idx in range(0, n_rows, batch_size):
        yield df.iloc[start_idx : min(start_idx + batch_size, n_rows)]
