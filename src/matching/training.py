# 3. ENTITY-LEVEL VALIDATION SPLITTING
# ==============================================================================

def create_entity_split(
    data_or_ids: Union[pd.DataFrame, pd.Series, Iterable[Any]],
    test_size: float = 0.2,
    random_state: int = 42,
    s1_col: str = "s1_entity_id",
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Split entities strictly at the S1 entity level.
    
    Guarantees that no S1 entity occurs in both the training and validation sets.
    This prevents data leakage and mimics real inference on unseen query entities.
    
    Args:
        data_or_ids: DataFrame containing s1_col, or a Series / iterable of unique S1 entity IDs.
        test_size: Proportion of S1 entities to allocate to validation (default: 0.2).
        random_state: Random seed for deterministic reproducibility.
        s1_col: Column name containing S1 entity IDs if DataFrame is passed.
        
    Returns:
        (train_s1_ids, val_s1_ids) as two 1D numpy arrays of entity IDs.
    """
    if isinstance(data_or_ids, pd.DataFrame):
        if s1_col not in data_or_ids.columns:
            raise ValueError(f"DataFrame must contain s1 entity column '{s1_col}'.")
        unique_s1_ids = data_or_ids[s1_col].unique()
    elif isinstance(data_or_ids, pd.Series):
        unique_s1_ids = data_or_ids.unique()
    else:
        unique_s1_ids = np.unique(list(data_or_ids))

    if len(unique_s1_ids) == 0:
        return np.array([], dtype=object), np.array([], dtype=object)

    if len(unique_s1_ids) == 1:
        # Edge case: single entity
        return unique_s1_ids, np.array([], dtype=object)

    train_s1_ids, val_s1_ids = train_test_split(
        unique_s1_ids,
        test_size=test_size,
        random_state=random_state,
        shuffle=True,
    )

    # Verification of zero entity overlap
    overlap = set(train_s1_ids).intersection(set(val_s1_ids))
    assert len(overlap) == 0, f"Entity leakage detected! Overlap: {len(overlap)} S1 IDs."

    logger.info(
        "Entity split created: %d train S1s, %d val S1s (val ratio %.2f, 0 overlap)",
        len(train_s1_ids),
        len(val_s1_ids),
        len(val_s1_ids) / len(unique_s1_ids),
    )
    return train_s1_ids, val_s1_ids


def split_pairs_by_entity(
    pairs_df: pd.DataFrame,
    train_s1_ids: Union[Iterable[Any], Set[Any]],
    val_s1_ids: Union[Iterable[Any], Set[Any]],
    s1_col: str = "s1_entity_id",
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Partition candidate pairs DataFrame into train and validation DataFrames
    given disjoint S1 entity ID sets.
    
    Args:
        pairs_df: DataFrame of candidate pairs.
        train_s1_ids: Iterable/set of S1 IDs allocated to training.
        val_s1_ids: Iterable/set of S1 IDs allocated to validation.
        s1_col: S1 entity ID column name.
        
    Returns:
        (train_pairs_df, val_pairs_df)
    """
    train_set = set(train_s1_ids)
    val_set = set(val_s1_ids)

    train_mask = pairs_df[s1_col].isin(train_set)
    val_mask = pairs_df[s1_col].isin(val_set)

    train_df = pairs_df[train_mask].reset_index(drop=True)
    val_df = pairs_df[val_mask].reset_index(drop=True)

    return train_df, val_df


